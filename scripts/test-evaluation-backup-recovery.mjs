import assert from 'node:assert/strict';
import { parseEvaluationRows, planRecovery, appendRecovery, verifyRecovery } from './evaluation-backup-recovery.mjs';

const headers = ['id', 'advisor_id', 'evaluator_id', 'evaluation_type', 'evaluated_at', 'payload_json', 'created_at'];
const row = (id, type = 'D3C', score = 85) => [id, 'advisor', 'user', type, '2026-09-07T10:00:00', JSON.stringify({ id, advisorId: 'advisor', evaluatorId: 'user', campaignId: 'campaign', evaluationType: type, date: '2026-09-07', items: [], scoreTotal: score }), '2026-09-07T15:00:00Z'];
const directories = { ADVISORS: [['id'], ['advisor']], CAMPAIGNS: [['id'], ['campaign']], USERS: [['id'], ['user']], TEAMS: [['id']] };
const current = [headers, ...Array.from({ length: 4 }, (_, i) => row(`new${i}`, 'QUALITY'))];
const backup = [headers, ...Array.from({ length: 58 }, (_, i) => row(`old${i}`, i < 48 ? 'QUALITY' : 'D3C'))];
const plan = planRecovery(current, backup, directories);
assert.equal(plan.summary.expectedTotal, 62);
assert.deepEqual(plan.summary.missingTypes, { QUALITY: 48, D3C: 10 });
let live = structuredClone(current), snapshots = 0, writes = 0;
const io = { read: async () => structuredClone(live), backup: async () => { snapshots++; }, append: async values => { writes++; live.push(...structuredClone(values)); } };
assert.deepEqual(await appendRecovery(plan, io), { verified: true, total: 62, added: 58, preserved: 4 });
const rerun = planRecovery(live, backup, directories);
assert.equal(rerun.summary.missing, 0);
await appendRecovery(rerun, io);
assert.equal(writes, 1);
assert.equal(snapshots, 1);
const conflict = planRecovery(current, [headers, row('new0', 'QUALITY', 1)], directories);
assert.equal(conflict.summary.preservedConflicts, 1);
assert.equal(conflict.summary.missing, 0);
assert.throws(() => parseEvaluationRows([headers, row('x'), row('x')]));
const invalid = row('invalid'); invalid[5] = '{';
assert.throws(() => parseEvaluationRows([headers, invalid]));
const mismatched = row('x'); mismatched[0] = 'other';
assert.throws(() => parseEvaluationRows([headers, mismatched]));
assert.throws(() => planRecovery(current, backup, { ...directories, ADVISORS: [['id']] }));
assert.throws(() => planRecovery(current, [headers], directories));
assert.throws(() => verifyRecovery(plan, current));
const changed = structuredClone(live); changed[1] = row('new0', 'QUALITY', 1);
assert.throws(() => verifyRecovery(plan, changed));
let unexpectedWrite = false;
await assert.rejects(appendRecovery(plan, { ...io, append: async () => { unexpectedWrite = true; } }));
assert.equal(unexpectedWrite, false);
let attempts = 0;
await assert.rejects(appendRecovery(plan, { read: async () => current, backup: async () => {}, append: async () => { attempts++; throw new Error('uncertain network result'); } }));
assert.equal(attempts, 1);
await assert.rejects(appendRecovery(plan, { read: async () => current, backup: async () => { throw new Error('backup failed'); }, append: async () => { unexpectedWrite = true; } }));
assert.equal(unexpectedWrite, false);
console.log('PASS: 58 + 4 = 62; preservation, idempotency, conflicts, malformed rows, references, concurrent changes and failed writes.');
